-- ═══════════════════════════════════════════════════════════════
-- Yoca — upgrade v16 (Insights newsletter)
--
-- New tables (nothing existing changes, except one widened check):
--   newsletter_subscribers   e-mail, language, status (pending → active →
--                            unsubscribed), double opt-in token (hash only,
--                            7-day expiry), unsubscribe token, the consent
--                            text the visitor saw and when, SHA-256 of the IP
--   newsletter_sends         one send per article group (unique), the time
--                            of the admin's test e-mail, counters
--   newsletter_deliveries    one row per subscriber per send (unique), so a
--                            send that stops half-way resumes without
--                            sending anybody a second copy
-- spam_log.form also accepts 'newsletter'.
--
-- Visitors never read or write these tables: the server uses the service
-- role. Signed-in admins (is_admin(), v10) may read them in the panel.
-- Requires v6, v10, v13. Additive and idempotent.
-- Undo (only if needed): drop table public.newsletter_deliveries,
--   public.newsletter_sends, public.newsletter_subscribers;
-- ═══════════════════════════════════════════════════════════════

begin;

do $$
begin
  if to_regprocedure('public.is_admin()') is null then
    raise exception 'v16 durduruldu: public.is_admin() yok (v10 gerekli).';
  end if;
  if to_regclass('public.insights') is null then
    raise exception 'v16 durduruldu: public.insights yok (v6 gerekli).';
  end if;
end;
$$;

create table if not exists public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  locale text not null default 'en' check (locale in ('en', 'tr', 'az', 'ar')),
  status text not null default 'pending' check (status in ('pending', 'active', 'unsubscribed')),
  confirm_token_hash text,
  confirm_expires_at timestamptz,
  confirm_sent_at timestamptz,
  unsubscribe_token text not null,
  consent_text text not null,
  consent_at timestamptz not null default now(),
  ip_hash text,
  source text,
  confirmed_at timestamptz,
  unsubscribed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint newsletter_email_lower check (email = lower(email))
);

create unique index if not exists newsletter_subscribers_email_key on public.newsletter_subscribers (email);
create unique index if not exists newsletter_subscribers_unsub_key on public.newsletter_subscribers (unsubscribe_token);
create index if not exists newsletter_subscribers_confirm_idx on public.newsletter_subscribers (confirm_token_hash) where confirm_token_hash is not null;
create index if not exists newsletter_subscribers_status_idx on public.newsletter_subscribers (status, locale);

create table if not exists public.newsletter_sends (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null,
  insight_id uuid references public.insights(id) on delete set null,
  status text not null default 'draft' check (status in ('draft', 'sending', 'sent', 'partial')),
  test_sent_at timestamptz,
  test_sent_to text,
  started_at timestamptz,
  finished_at timestamptz,
  recipients integer not null default 0,
  sent integer not null default 0,
  failed integer not null default 0,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists newsletter_sends_group_key on public.newsletter_sends (group_id);

create table if not exists public.newsletter_deliveries (
  id bigint generated by default as identity primary key,
  send_id uuid not null references public.newsletter_sends(id) on delete cascade,
  subscriber_id uuid not null references public.newsletter_subscribers(id) on delete cascade,
  locale text not null,
  status text not null default 'queued' check (status in ('queued', 'sent', 'failed', 'skipped')),
  provider_id text,
  error text,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

create unique index if not exists newsletter_deliveries_unique on public.newsletter_deliveries (send_id, subscriber_id);
create index if not exists newsletter_deliveries_queue on public.newsletter_deliveries (send_id, status);

alter table public.newsletter_subscribers enable row level security;
alter table public.newsletter_sends enable row level security;
alter table public.newsletter_deliveries enable row level security;

drop policy if exists "admin read newsletter subscribers" on public.newsletter_subscribers;
create policy "admin read newsletter subscribers" on public.newsletter_subscribers for select to authenticated using (public.is_admin());
drop policy if exists "admin read newsletter sends" on public.newsletter_sends;
create policy "admin read newsletter sends" on public.newsletter_sends for select to authenticated using (public.is_admin());
drop policy if exists "admin read newsletter deliveries" on public.newsletter_deliveries;
create policy "admin read newsletter deliveries" on public.newsletter_deliveries for select to authenticated using (public.is_admin());

revoke all on public.newsletter_subscribers, public.newsletter_sends, public.newsletter_deliveries from anon;

-- spam_log: newsletter sign-ups are screened too.
do $$
declare c text;
begin
  select conname into c from pg_constraint where conrelid = 'public.spam_log'::regclass and contype = 'c' and pg_get_constraintdef(oid) like '%form%';
  if c is not null then execute format('alter table public.spam_log drop constraint %I', c); end if;
  alter table public.spam_log add constraint spam_log_form_check check (form in ('contact', 'checkup', 'newsletter'));
end;
$$;

commit;
